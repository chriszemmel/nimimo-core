export function generateHandle(): string {
  const values = new Uint32Array(2)
  crypto.getRandomValues(values)
  const adjective = ADJECTIVES[values[0] % ADJECTIVES.length]
  const noun = NOUNS[values[1] % NOUNS.length]
  return `${adjective}-${noun}`
}

/**
 * Generate a handle with a numeric suffix for collision recovery.
 * Called when the base 2-word handle space is congested.
 */
export function generateHandleWithSuffix(): string {
  const values = new Uint32Array(3)
  crypto.getRandomValues(values)
  const adjective = ADJECTIVES[values[0] % ADJECTIVES.length]
  const noun = NOUNS[values[1] % NOUNS.length]
  const suffix = (values[2] % 998) + 2 // 2-999
  return `${adjective}-${noun}-${suffix}`
}
